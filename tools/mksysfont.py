"""mksysfont.py - build src/sysfont.c, XGDOS's own system fonts.

XGDOS draws system font text on its memory device without the ROM's
fonts (Line-A, the only way to reach them, is deprecated on later TOS
versions), so it carries the three EmuTOS system fonts in the Atari ST
character set:

  6x6   bios/fnt_st_6x6.c    (8 point)
  8x8   bios/fnt_st_8x8.c    (9 point)
  8x16  bios/fnt_st_8x16.c   (10 point)

They are Copyright (C) 2001-2021 The EmuTOS development team and
distributed under the GNU GPL, version 2 or (at your option) any later
version; see LICENSE.

usage: mksysfont.py EMUTOS_DIR > src/sysfont.c
"""
import os, re, sys


def field(text, name):
    m = re.search(r'(\d+)\s*,\s*/\*\s*U?WORD\s+' + name + r'\b', text)
    if not m:
        raise SystemExit('no %s in font header' % name)
    return int(m.group(1))


def load(path):
    text = open(path, encoding='latin-1').read()
    body = text[re.search(r'dat_table\[\d*\]', text).start():]
    body = body[body.index('{') + 1:body.index('};')]
    words = [int(w, 16) for w in re.findall(r'0x([0-9A-Fa-f]{1,4})', body)]
    hdr = text[text.index('const Fonthead'):]
    f = {k: field(hdr, k) for k in ('top', 'ascent', 'half', 'descent', 'bottom',
                                    'max_cell_width', 'form_width', 'form_height')}
    fw, fh, cw = f['form_width'], f['form_height'], f['max_cell_width']
    data = b''.join(bytes([w >> 8, w & 0xff]) for w in words)
    if len(data) < fw * fh:
        raise SystemExit('%s: short dat_table' % path)
    glyphs = []
    for c in range(256):
        rows = []
        for y in range(fh):
            v = 0
            for x in range(cw):             # monospaced: glyph c starts at c * width
                bit = c * cw + x
                if data[y * fw + (bit >> 3)] & (0x80 >> (bit & 7)):
                    v |= 0x80 >> x
            rows.append(v)
        glyphs.append(rows)
    return glyphs, cw, fh, f


def emit(name, g, w, h, f):
    print('static const u8 %s_bits[256 * %d] = {' % (name, h))
    for c in range(256):
        print('    ' + ', '.join('0x%02x' % v for v in g[c]) + ',  /* %02X */' % c)
    print('};')
    return '{ %d, %d, %d, %d, %d, %d, %d, %s_bits }' % (
        w, h, f['top'], f['ascent'], f['half'], f['descent'], f['bottom'], name)


def main():
    d = os.path.join(sys.argv[1], 'bios')
    fonts = [('sf6x6', 'fnt_st_6x6.c'), ('sf8x8', 'fnt_st_8x8.c'), ('sf8x16', 'fnt_st_8x16.c')]
    print('''/* SPDX-License-Identifier: GPL-2.0-only
 * Copyright (c) 2026 Francis C Bullen - see LICENSE
 *
 * sysfont.c - XGDOS's own system fonts in the Atari ST character set.
 * GENERATED by tools/mksysfont.py - do not edit by hand.
 *
 * The glyphs are the EmuTOS system fonts (bios/fnt_st_6x6.c, fnt_st_8x8.c,
 * fnt_st_8x16.c): Copyright (C) 2001-2021 The EmuTOS development team,
 * distributed under the GNU General Public License, version 2 or (at
 * your option) any later version. See LICENSE and README.md.
 */
#include "sysfont.h"
''')
    out = []
    for name, fn in fonts:
        g, w, h, f = load(os.path.join(d, fn))
        print('/* %s: EmuTOS %s */' % (name, fn))
        out.append(emit(name, g, w, h, f))
    print('\nconst SysFont xg_sysfonts[3] = {\n    %s,\n    %s,\n    %s\n};' % tuple(out))


main()
